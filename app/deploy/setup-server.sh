#!/usr/bin/env bash
# One-time (idempotent) server setup. Run on the server: sudo bash /opt/callcenter/deploy/setup-server.sh
set -euo pipefail
APP=/opt/callcenter
ETC=/etc/callcenter
IP=${SERVER_IP:-$(hostname -I | awk '{print $1}')}
mkdir -p $ETC/tls /var/lib/callcenter /var/backups/callcenter

# ---- secrets (generated once)
if [ ! -f $ETC/api.env ]; then
  rnd() { openssl rand -hex 16; }
  DBP=$(rnd); cat > $ETC/api.env <<ENV
NODE_ENV=production
PORT=3000
TZ_REGION=Asia/Tehran
DATABASE_URL=postgresql://callcenter:$DBP@127.0.0.1:5432/callcenter
JWT_SECRET=$(rnd)$(rnd)
AMI_HOST=127.0.0.1
AMI_PORT=5038
AMI_USER=ccapi
AMI_SECRET=$(rnd)
HOOK_SECRET=$(rnd)
HOOK_URL=http://127.0.0.1:3000/api/hooks
ASTERISK_CC_CONF_DIR=/etc/asterisk/cc
ASTERISK_SOUNDS_DIR=/var/lib/asterisk/sounds/custom
ASTERISK_MOH_DIR=/var/lib/asterisk/moh-cc
ASTERISK_MONITOR_DIR=/var/spool/asterisk/monitor
DEMO_AUDIO=/var/lib/callcenter/demo.wav
# Clinic booking system (patient lookup by mobile). Fill in to enable:
CLINIC_API_URL=
CLINIC_API_TOKEN=
CLINIC_LOOKUP_PATH=/patients?mobile={phone}
# Persian speech-to-text service (POST multipart file -> {text, confidence}). Empty = AI analysis pending.
STT_URL=
ENV
  chmod 640 $ETC/api.env; chgrp asterisk $ETC/api.env
fi
set -a; . $ETC/api.env; set +a
DBP=$(echo "$DATABASE_URL" | sed -E 's#.*callcenter:([^@]+)@.*#\1#')

# ---- PostgreSQL
sudo -u postgres psql -tAc "SELECT 1 FROM pg_roles WHERE rolname='callcenter'" | grep -q 1 || sudo -u postgres psql -c "CREATE ROLE callcenter LOGIN PASSWORD '$DBP'"
sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='callcenter'" | grep -q 1 || sudo -u postgres psql -c "CREATE DATABASE callcenter OWNER callcenter ENCODING 'UTF8' TEMPLATE template0"

# ---- Asterisk base configuration (generated files go to /etc/asterisk/cc)
mkdir -p /etc/asterisk/cc /var/lib/asterisk/sounds/custom /var/lib/asterisk/moh-cc /var/spool/asterisk/monitor/cc /var/spool/asterisk/monitor/cc-vm
rm -f /etc/asterisk/extensions.ael /etc/asterisk/extensions.lua /etc/asterisk/users.conf
for f in $APP/asterisk/conf/*.conf; do
  sed -e "s#@AMI_SECRET@#$AMI_SECRET#" -e "s#@DB_PASSWORD@#$DBP#" "$f" > /etc/asterisk/$(basename "$f")
done
for f in pjsip extensions queues musiconhold; do [ -f /etc/asterisk/cc/$f.conf ] || echo "; generated by the panel" > /etc/asterisk/cc/$f.conf; done
chown -R asterisk:asterisk /etc/asterisk /var/lib/asterisk /var/spool/asterisk /var/log/asterisk /var/lib/callcenter
chmod -R g+rwX /etc/asterisk/cc /var/lib/asterisk/sounds/custom /var/lib/asterisk/moh-cc /var/spool/asterisk/monitor
chmod 640 /etc/asterisk/manager.conf /etc/asterisk/cdr_pgsql.conf
mkdir -p /etc/systemd/system/asterisk.service.d
printf '[Service]\nType=simple\nUMask=0002\nRuntimeDirectory=asterisk\nRuntimeDirectoryMode=0775\n' > /etc/systemd/system/asterisk.service.d/override.conf

# demo recording used by the sample (seeded) calls + placeholder prompts for the sample sounds
[ -f /var/lib/callcenter/demo.wav ] || ffmpeg -v error -f lavfi -i "sine=frequency=320:duration=60" -f lavfi -i "anoisesrc=d=60:c=pink:a=0.04" -filter_complex "[0]volume='0.25*(0.6+0.4*sin(2*PI*t/2.7))':eval=frame[a];[a][1]amix=inputs=2" -ar 8000 -ac 1 /var/lib/callcenter/demo.wav
for s in s1:18 s2:60 s3:12 s4:22 s5:26 s6:15 s7:14; do id=${s%%:*}; d=${s##*:}
  [ -f /var/lib/asterisk/sounds/custom/$id.wav ] || ffmpeg -v error -f lavfi -i "sine=frequency=520:duration=0.4,apad=pad_dur=$((d>8?8:d))" -ar 8000 -ac 1 -sample_fmt s16 /var/lib/asterisk/sounds/custom/$id.wav
done
chown -R asterisk:asterisk /var/lib/asterisk/sounds/custom /var/lib/callcenter

# ---- API service
cat > /etc/systemd/system/callcenter-api.service <<UNIT
[Unit]
Description=Aflaki call center API
After=network.target postgresql.service asterisk.service
Wants=asterisk.service

[Service]
User=asterisk
Group=asterisk
WorkingDirectory=$APP/api
EnvironmentFile=$ETC/api.env
ExecStart=/usr/bin/node dist/main.js
Restart=always
RestartSec=3
UMask=0002

[Install]
WantedBy=multi-user.target
UNIT

# ---- TLS (self-signed for the LAN IP) + nginx
if [ ! -f $ETC/tls/cert.pem ]; then
  openssl req -x509 -nodes -newkey rsa:2048 -days 3650 -keyout $ETC/tls/key.pem -out $ETC/tls/cert.pem \
    -subj "/CN=$IP/O=Aflaki Call Center" -addext "subjectAltName=IP:$IP,DNS:localhost"
  chmod 600 $ETC/tls/key.pem
fi
cat > /etc/nginx/sites-available/callcenter <<NGX
server { listen 80 default_server; return 301 https://\$host\$request_uri; }
server {
  listen 443 ssl default_server;
  http2 on;
  ssl_certificate $ETC/tls/cert.pem;
  ssl_certificate_key $ETC/tls/key.pem;
  root $APP/web/dist;
  client_max_body_size 50m;
  add_header X-Content-Type-Options nosniff always;
  add_header X-Frame-Options SAMEORIGIN always;
  location /api/backups/upload { client_max_body_size 20g; proxy_request_buffering off; proxy_pass http://127.0.0.1:3000; proxy_read_timeout 1h; proxy_send_timeout 1h; }
  location /api/ { proxy_pass http://127.0.0.1:3000; proxy_set_header Host \$host; proxy_set_header X-Forwarded-For \$remote_addr; proxy_read_timeout 300s; }
  location /socket.io/ { proxy_pass http://127.0.0.1:3000; proxy_http_version 1.1; proxy_set_header Upgrade \$http_upgrade; proxy_set_header Connection "upgrade"; proxy_read_timeout 1h; }
  location /ws { proxy_pass http://127.0.0.1:8088/ws; proxy_http_version 1.1; proxy_set_header Upgrade \$http_upgrade; proxy_set_header Connection "upgrade"; proxy_read_timeout 1h; }
  location /assets/ { expires 30d; add_header Cache-Control "public, immutable"; }
  location / { try_files \$uri /index.html; add_header Cache-Control "no-cache"; }
}
NGX
ln -sf /etc/nginx/sites-available/callcenter /etc/nginx/sites-enabled/callcenter
rm -f /etc/nginx/sites-enabled/default
nginx -t

# ---- nightly database backup (14 days kept)
cat > /etc/cron.d/callcenter-backup <<'CRON'
30 2 * * * postgres pg_dump callcenter | gzip > /var/backups/callcenter/db-$(date +\%F).sql.gz && find /var/backups/callcenter -name 'db-*.sql.gz' -mtime +14 -delete
CRON
chown postgres /var/backups/callcenter

# ---- firewall: SSH, HTTPS, SIP, RTP
ufw allow 22/tcp >/dev/null; ufw allow 80/tcp >/dev/null; ufw allow 443/tcp >/dev/null
ufw allow 5060/udp >/dev/null; ufw allow 10000:20000/udp >/dev/null
ufw --force enable >/dev/null

systemctl daemon-reload
systemctl enable asterisk callcenter-api nginx postgresql >/dev/null
systemctl restart asterisk
systemctl reload nginx
echo SETUP_DONE
